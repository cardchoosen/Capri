package ai.capri.app.nativebridge

import org.json.JSONObject
import java.io.File

internal data class RootRequest(val command: String, val timeoutSeconds: Int, val outputLimit: Int)

/** Commands go into a file verbatim, never into the su command line or a trusted supervisor. */
internal object RootProtocol {
    /** Keep valid JSON below the Agent's tool-result character limit, even for escaped control bytes. */
    fun boundedOutput(stdout: String, stderr: String): Pair<String, String> {
        fun fit(text: String, budget: Int): String {
            if (JSONObject.quote(text).length <= budget) return text
            var low = 0; var high = text.length
            while (low < high) {
                val mid = (low + high + 1) / 2
                if (JSONObject.quote(text.take(mid)).length <= budget) low = mid else high = mid - 1
            }
            if (low > 0 && text[low - 1].isHighSurrogate()) low--
            return text.take(low)
        }
        val out = fit(stdout, 30000)
        return out to fit(stderr, 30000 - JSONObject.quote(out).length)
    }
    fun request(params: JSONObject): RootRequest {
        val command = params.requiredText("command", 32000)
        if ('\u0000' in command) throw NativeFailure("invalid_argument", "command不能含NUL")
        return RootRequest(command, params.boundedInt("timeout_seconds", 30, 1, 120), params.boundedInt("output_limit", 16000, 1000, 64000))
    }
    fun quote(value: String) = "'" + value.replace("'", "'\\''") + "'"
    fun launch(su: String, directory: File) = listOf(su, "-c", "exec /system/bin/setsid -w /system/bin/sh ${quote(File(directory, "supervisor.sh").path)}")
    fun supervisor(directory: File, cwd: File, lifetimeSeconds: Int): String = """
        #!/system/bin/sh
        # All interpolated values are generated by the application, not command contents.
        cd ${quote(directory.path)} || exit 125
        umask 022
        uid=${'$'}(/system/bin/id -u) || exit 126
        [ "${'$'}uid" = 0 ] || exit 126
        stat=${'$'}(cat /proc/${'$'}${'$'}/stat) || exit 125
        fields=${'$'}{stat##*) }
        set -- ${'$'}fields
        [ "${'$'}3" = "${'$'}${'$'}" ] && [ "${'$'}4" = "${'$'}${'$'}" ] || exit 125
        shift 19
        printf '%s %s 0\n' "${'$'}${'$'}" "${'$'}1" > identity
        # This watchdog belongs to the same process group. It also bounds work if the app dies.
        ( sleep $lifetimeSeconds; kill -KILL -${'$'}${'$'} ) >/dev/null 2>&1 &
        # No user command may start until the app has observed a genuine root identity.
        while [ ! -s release ]; do sleep 0.05; done
        cd ${quote(cwd.path)} || { printf '125\n' > ${quote(File(directory, "done").path)}; while :; do sleep 1; done; }
        /system/bin/sh ${quote(File(directory, "command.sh").path)} < /dev/null > ${quote(File(directory, "stdout").path)} 2> ${quote(File(directory, "stderr").path)} &
        child=${'$'}!
        wait "${'$'}child"
        code=${'$'}?
        printf '%s\n' "${'$'}code" > ${quote(File(directory, "done").path)}
        # Remain alive until native cleanup, so PID/start-time identity remains verifiable.
        while :; do sleep 1; done
    """.trimIndent() + "\n"

    fun cleanup(directory: File): String = """
        cd ${quote(directory.path)} || exit 125
        read pid started uid < identity || exit 125
        case "${'$'}pid:${'$'}started:${'$'}uid" in *[!0-9:]*|'') exit 125;; esac
        [ "${'$'}uid" = 0 ] && [ "${'$'}pid" -gt 1 ] || exit 125
        [ -r "/proc/${'$'}pid/stat" ] || exit 0
        stat=${'$'}(cat "/proc/${'$'}pid/stat") || exit 125
        fields=${'$'}{stat##*) }
        set -- ${'$'}fields
        [ "${'$'}3" = "${'$'}pid" ] && [ "${'$'}4" = "${'$'}pid" ] || exit 125
        shift 19
        [ "${'$'}1" = "${'$'}started" ] || exit 125
        kill -KILL -"${'$'}pid" || exit 125
        attempt=0
        while kill -0 -"${'$'}pid" 2>/dev/null; do
            attempt=${'$'}((attempt + 1))
            [ "${'$'}attempt" -lt 30 ] || exit 125
            sleep 0.05
        done
        exit 0
    """.trimIndent()
}
